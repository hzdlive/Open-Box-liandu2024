"""DNS filter (ad/malware blocklists) — panel-side management.

Clean-room reimplementation of the publicly observable behavior:
- subscribe to hosts-format / adblock-style blocklists,
- compile them into one domain set,
- enforce via dnsmasq ``address=/domain/#`` lines (NXDOMAIN) so it works
  with the stock dnsmasq takeover path and needs no kernel support,
- match live queries from the dnsmasq query log for records/preview.

Enforcement file: ``<workdir>/dnsmasq-blocklist.conf``; the generated
dnsmasq snippet includes it with ``conf-file=`` when the filter is on.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import threading
import time
import urllib.request

# hosts line: "0.0.0.0 example.com" / "127.0.0.1 example.com"
_HOSTS_RE = re.compile(r"^(?:0\.0\.0\.0|127\.0\.0\.1|::1?)\s+(\S+)", re.I)
# adblock basic: "||example.com^"
_ADBLOCK_RE = re.compile(r"^\|\|([a-z0-9_.-]+)\^?$", re.I)

BUILTIN_LISTS = [
    {"name": "AdGuard DNS filter",
     "url": "https://adguardteam.github.io/HostlistsRegistry/assets/filter_1.txt",
     "enabled": True},
    {"name": "StevenBlack hosts",
     "url": "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts",
     "enabled": False},
]


def parse_list(text: str) -> set[str]:
    """Parse hosts/adblock-basic formats into a domain set."""
    domains: set[str] = set()
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(("#", "!", "[")):
            continue
        m = _HOSTS_RE.match(line)
        if m:
            d = m.group(1).lower().strip(".")
            if d and d != "localhost":
                domains.add(d)
            continue
        m = _ADBLOCK_RE.match(line)
        if m:
            domains.add(m.group(1).lower().strip("."))
    return domains


def fetch_list(url: str, timeout: float = 30.0) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "openbox-oss/1.0"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


def match_domain(domain: str, compiled: set[str]) -> str | None:
    """Suffix-match a query domain against the compiled set. Returns the
    matched blocklist entry (the most specific suffix) or None."""
    d = domain.lower().strip(".").rstrip(".")
    while d:
        if d in compiled:
            return d
        if "." not in d:
            break
        d = d.split(".", 1)[1]
    return None


def blocklist_path(workdir: str) -> str:
    return os.path.join(workdir, "dnsmasq-blocklist.conf")


def write_blocklist(workdir: str, compiled: dict[str, set[str]]) -> tuple[int, str]:
    """Write dnsmasq address= lines. Returns (domain count, path)."""
    path = blocklist_path(workdir)
    total: set[str] = set()
    for domains in compiled.values():
        total |= domains
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Generated by openbox-oss DNS filter — do not edit\n")
        for d in sorted(total):
            f.write(f"address=/{d}/#\n")
    return len(total), path


def blocklist_hash(workdir: str) -> str | None:
    """sha256 of the written blocklist file, or None if it is missing.

    Used to tell whether an apply actually changed the file dnsmasq
    reads: the panel drop-in only references the file by path, so a
    content change is invisible to the drop-in diff.
    """
    import hashlib
    try:
        h = hashlib.sha256()
        with open(blocklist_path(workdir), "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
        return h.hexdigest()
    except OSError:
        return None


def load_compiled(workdir: str) -> set[str]:
    """Load the compiled set back from the written file (for matching)."""
    path = blocklist_path(workdir)
    domains: set[str] = set()
    try:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line.startswith("address=/") and line.endswith("/#"):
                    domains.add(line[len("address=/"):-len("/#")])
    except OSError:
        pass
    return domains


# Single-flight lock for POST /api/dns/filter/apply (v7 #24 semantics):
# while an apply holds it, another apply answers 400 and PUT /api/dns/filter
# answers 409. The lock lives here so the endpoint, the settings PUT and
# the GET busy flag all observe the same flag.
_APPLY_LOCK = threading.Lock()


def apply_lists(workdir: str, lists: list[dict],
                timeout: float = 30.0) -> dict:
    """Fetch + compile + write. Returns per-list stats."""
    compiled: dict[str, set[str]] = {}
    stats = []
    for lst in lists:
        if not lst.get("enabled", True):
            stats.append({"name": lst["name"], "enabled": False,
                          "domains": 0, "error": ""})
            continue
        try:
            text = fetch_list(lst["url"], timeout=timeout)
            domains = parse_list(text)
            compiled[lst["name"]] = domains
            stats.append({"name": lst["name"], "enabled": True,
                          "domains": len(domains),
                          "updated_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
                          "error": ""})
        except Exception as e:  # keep other lists working
            stats.append({"name": lst["name"], "enabled": True,
                          "domains": 0, "error": str(e)[:120]})
    enabled_stats = [s for s in stats if s["enabled"]]
    if enabled_stats and all(s["error"] for s in enabled_stats):
        # Fail closed: every enabled list failed, so the old blocklist
        # stays. Writing an empty union here would silently turn
        # filtering off for every domain. (Zero enabled lists is not
        # this case: disabling everything legitimately empties the file.)
        return {"all_failed": True, "total_domains": 0,
                "path": blocklist_path(workdir), "lists": stats,
                "dnsmasq_reloaded": False, "applied_at": ""}
    total, path = write_blocklist(workdir, compiled)
    # No HUP here on purpose: SIGHUP does not reload dnsmasq config
    # files (verified live 2026-10-25), so signalling would only fake a
    # reload. Restarting dnsmasq when this file changed is the panel
    # sync's job (sync_dnsmasq_panel_conf with force_restart).
    return {"all_failed": False, "total_domains": total, "path": path,
            "lists": stats, "dnsmasq_reloaded": False,
            "applied_at": time.strftime("%Y-%m-%dT%H:%M:%S")}


# ---------------------------------------------------------------------------
# Kernel-side enforcement (aligned with the original core, v0.1.337 golden):
# the original does NOT block ad domains in route rules. It shards the
# blocklist into local rule-set files (dns-filter-anti-ad-block[-2..-4]
# + dns-filter-anti-ad-allow) and answers NXDOMAIN for them in the DNS
# module (predefined + rcode NXDOMAIN, mode and, unless allow-listed).
# This module writes the same shape as sing-box JSON source rule-sets
# (format "source"; the original uses binary .srs, behaviorally identical
# for domain_suffix matching) so build_config can reference them.
# ---------------------------------------------------------------------------

KERNEL_RULESET_DIR = "dns-filter"
KERNEL_BLOCK_TAG = "dns-filter-anti-ad-block"
KERNEL_ALLOW_TAG = "dns-filter-anti-ad-allow"
KERNEL_SHARD_SIZE = 25000
# Sentinel: keeps the allow rule-set non-empty when the panel has no
# allow list (mirrors the obnode-direct.invalid sentinel). Matches nothing.
ALLOW_SENTINEL = "dns-filter-allow.invalid"


def kernel_shard_tags(n_domains: int) -> list[str]:
    """Shard tags for a blocklist of n_domains (original: 4 shards)."""
    if n_domains <= 0:
        return []
    n = (n_domains + KERNEL_SHARD_SIZE - 1) // KERNEL_SHARD_SIZE
    return [KERNEL_BLOCK_TAG if i == 0 else f"{KERNEL_BLOCK_TAG}-{i + 1}"
            for i in range(n)]


def _write_if_changed(path: str, content: str) -> bool:
    """Write content unless the file already has it. Returns True if written."""
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == content:
                return False
    except OSError:
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(content)
    os.replace(tmp, path)
    return True


def kernel_ruleset_entries(workdir: str, domains, allow=None) -> list[dict]:
    """Deterministic [{tag, path}] for the kernel rule-sets, without writing.

    Previews use this so the shown config matches what apply will emit
    (apply writes the files first via write_kernel_rulesets).
    """
    d = sorted({x.lower().strip(".") for x in (domains or []) if x})
    tags = kernel_shard_tags(len(d))
    base = os.path.join(workdir, KERNEL_RULESET_DIR)
    out = [{"tag": t, "path": os.path.join(base, f"{t}.json")} for t in tags]
    out.append({"tag": KERNEL_ALLOW_TAG,
                "path": os.path.join(base, f"{KERNEL_ALLOW_TAG}.json")})
    return out


def write_kernel_rulesets(workdir: str, domains, allow=None) -> list[dict]:
    """Write the kernel-side DNS-filter rule-set files.

    domains: the blocked domain list (flat). allow: optional allow-list
    domains (None = no allow list -> sentinel file). Returns
    [{"tag": ..., "path": ...}] for the block shards + the allow set,
    in declaration order (blocks first, allow last). Files are only
    rewritten when their content changed.
    """
    d = sorted({x.lower().strip(".") for x in (domains or []) if x})
    entries = kernel_ruleset_entries(workdir, domains, allow)
    for i, entry in enumerate(entries):
        if entry["tag"] == KERNEL_ALLOW_TAG:
            allow_domains = sorted({x.lower().strip(".")
                                    for x in (allow or []) if x})
            if not allow_domains:
                allow_domains = [ALLOW_SENTINEL]
            chunk = allow_domains
        else:
            chunk = d[i * KERNEL_SHARD_SIZE:(i + 1) * KERNEL_SHARD_SIZE]
        content = json.dumps({"version": 3,
                              "rules": [{"domain_suffix": chunk}]},
                             ensure_ascii=False, separators=(",", ":"))
        _write_if_changed(entry["path"], content)
    return entries
